"""FastAPI server exposing two AG-UI agents:

  POST /fixed/   . fixed-schema PDF dashboard using fixed A2UI schemas
  POST /dynamic/ . dynamic A2UI surfaces generated at runtime

Run with:  uvicorn main:app --port 8123 --reload
"""

from __future__ import annotations

import os

import uvicorn
from ag_ui_langgraph import add_langgraph_fastapi_endpoint
from copilotkit import LangGraphAGUIAgent
from dotenv import load_dotenv
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

load_dotenv()

# Patch ag-ui-langgraph's multimodal converter so PDF text shipped via
# CopilotChat attachments survives the trip to the model API. Must run BEFORE
# the agent graphs are imported so the agents pick up the patched
# converter at first message conversion.
from src.multimodal_middleware import install as _install_doc_inlining  # noqa: E402

_install_doc_inlining()

from src.dynamic_agent import graph as dynamic_graph  # noqa: E402
from src.fixed_agent import graph as fixed_graph  # noqa: E402
from src.models import AGENT_RECURSION_LIMIT  # noqa: E402

app = FastAPI(title="A2UI Demo Agents")


# Only the Next.js runtime calls these endpoints, server to server, and it
# sends no Origin header. Browsers always send one on a POST, including the
# no-CORS requests that a CORS policy cannot stop: refusing it keeps any web
# page open in the operator's browser from running the agents and spending
# the Mistral quota.
@app.middleware("http")
async def reject_browser_requests(request: Request, call_next):
    if "origin" in request.headers:
        return JSONResponse(
            {"detail": "Browser requests are not accepted."}, status_code=403
        )
    return await call_next(request)


# LangGraph's default recursion_limit is 25. ag_ui_langgraph builds its own
# RunnableConfig per run, which overrides any `.with_config()` we bind at
# compile time on the graph. Pass recursion_limit here so it's honored.
# The value is measured (see AGENT_RECURSION_LIMIT): just above the longest
# legitimate turn, so a looping model is cut short instead of running on.
_AGENT_CONFIG = {"recursion_limit": AGENT_RECURSION_LIMIT}

add_langgraph_fastapi_endpoint(
    app=app,
    agent=LangGraphAGUIAgent(
        name="fixed_agent",
        description="Fixed-schema PDF dashboard with fixed A2UI schemas.",
        graph=fixed_graph,
        config=_AGENT_CONFIG,
    ),
    path="/fixed",
)

add_langgraph_fastapi_endpoint(
    app=app,
    agent=LangGraphAGUIAgent(
        name="dynamic_agent",
        description="Dynamic A2UI surfaces generated by a secondary LLM.",
        graph=dynamic_graph,
        config=_AGENT_CONFIG,
    ),
    path="/dynamic",
)


@app.get("/")
def root():
    return {
        "ok": True,
        "agents": {
            "fixed_agent": "/fixed/",
            "dynamic_agent": "/dynamic/",
        },
    }


def main():
    # uvicorn's default host (127.0.0.1) keeps the agent off the network.
    uvicorn.run(
        "main:app",
        port=int(os.environ.get("PORT", "8123")),
        reload=True,
    )


if __name__ == "__main__":
    main()
